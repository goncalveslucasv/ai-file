// Builds the Rust codecs (wasm/) and embeds the module in src/wasm/binary.ts.
//   node scripts/build-wasm.ts
// Requires cargo with the wasm32-unknown-unknown target, and a clang that can target wasm32 for
// libzstd (C): set WASI_SDK_PATH to a wasi-sdk install, or CC_wasm32_unknown_unknown directly.
// On Linux the distribution clang works as is.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const env = { ...process.env };
const home = process.env.HOME ?? "";
if (home && !env.PATH?.split(path.delimiter).some((p) => fs.existsSync(path.join(p, "cargo")))) {
  env.PATH = `${path.join(home, ".cargo/bin")}${path.delimiter}${env.PATH ?? ""}`;
}
if (env.WASI_SDK_PATH && !env.CC_wasm32_unknown_unknown) {
  env.CC_wasm32_unknown_unknown = path.join(env.WASI_SDK_PATH, "bin/clang");
  env.AR_wasm32_unknown_unknown = path.join(env.WASI_SDK_PATH, "bin/llvm-ar");
}
execFileSync("cargo", ["build", "--release"], { cwd: path.join(root, "wasm"), stdio: "inherit", env });
const wasm = fs.readFileSync(path.join(root, "wasm/target/wasm32-unknown-unknown/release/ai_file_wasm.wasm"));
const b64 = wasm.toString("base64");
fs.writeFileSync(
  path.join(root, "src/wasm/binary.ts"),
  `// Generated by scripts/build-wasm.ts from wasm/ — do not edit.\n// ${wasm.length} bytes\nexport const WASM_BASE64: string = "${b64}";\n`,
);
console.log(`src/wasm/binary.ts: ${wasm.length} bytes of wasm`);
